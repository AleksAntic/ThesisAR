using UnityEngine;
using System.Collections.Generic;
using UnityEngine.AI;
using Unity.AI.Navigation;

/// <summary>
/// Central automation layer for the Bergen-Belsen NavMesh environment layout.
/// Features a real-time proximity gap detector that renders visual blue lines in the Scene View
/// for unlinked road nodes within a custom threshold, and provides a one-click automated patching engine.
/// All internal code, variables, and logs are strictly maintained in English.
/// </summary>
public class BergenBelsenNavMeshAutomator : MonoBehaviour
{
    [System.Serializable]
    public class RoadPathSegment
    {
        public string roadLabelName = "Branching Segment";
        public List<Vector3> roadCenterPoints = new List<Vector3>();
    }

    [Header("💾 Legacy Data Preservation (DO NOT DELETE)")]
    [Tooltip("This list preserves your original manually placed points to ensure zero data loss.")]
    [SerializeField] private List<Vector3> roadCenterPoints = new List<Vector3>();

    [Header("📐 Architectural Hierarchy References")]
    [SerializeField] private Transform buildingsRootNode;
    [SerializeField] private Transform terrainRootNode;

    [Header("🛣️ Branching Roads Network Settings")]
    [SerializeField] private float roadWidth = 6f;
    [Tooltip("Multi-segment containers for mapping out intersections and distinct streets smoothly.")]
    [SerializeField] private List<RoadPathSegment> roadSegments = new List<RoadPathSegment>();

    [Header("🔍 Automated Gap Proximity Scanner")]
    [Tooltip("Distance threshold (in meters) below which unlinked roads are flagged as gaps and highlighted in blue.")]
    [SerializeField] private float gapDetectionRadius = 5f;

    [Header("🎨 NavMesh Area Overrides")]
    [SerializeField] private string roadAreaName = "Walkable_Roads";

    [Header("🛡️ Visual Layer Isolation (AR Culling)")]
    [SerializeField] private string roadLayerName = "MapMarkers";

    public float RoadWidth => roadWidth;
    public List<RoadPathSegment> RoadSegments => roadSegments;
    public Transform BuildingsRootNode => buildingsRootNode;

    private void Awake()
    {
        if (Application.isPlaying)
        {
            // Destroy procedural modifiers root
            GameObject modifiersRoot = GameObject.Find("Procedural_NavMesh_Modifiers_Root");
            if (modifiersRoot != null) Destroy(modifiersRoot);

            // Scan and destroy all procedural roads and autogenerated vector roads to save massive performance/RAM
            GameObject[] allGo = UnityEngine.Object.FindObjectsByType<GameObject>(FindObjectsInactive.Include);
            foreach (var go in allGo)
            {
                if (go != null && (go.name.Contains("Procedural_Roads_Container") || go.name.Contains("Autogenerated_Vector_Road")))
                {
                    Destroy(go);
                }
            }
        }
    }

#if UNITY_EDITOR
    [ContextMenu("🔄 1. Migrate Old Road Data to Segments")]
    public void MigrateOldRoadDataToSegments()
    {
        if (roadCenterPoints != null && roadCenterPoints.Count > 0)
        {
            UnityEditor.Undo.RecordObject(this, "Migrate Legacy Road Data");

            RoadPathSegment migratedSegment = new RoadPathSegment
            {
                roadLabelName = "Migrated Original Route Base",
                roadCenterPoints = new List<Vector3>(roadCenterPoints)
            };

            if (roadSegments == null) roadSegments = new List<RoadPathSegment>();
            roadSegments.Insert(0, migratedSegment);

            Debug.Log("<color=cyan>[Automator Data Protection]</color> Legacy coordinates successfully migrated into the branching segments list! Your original data is safe.");
        }
        else
        {
            Debug.LogWarning("[Automator Data Protection] No legacy data found inside 'roadCenterPoints' to migrate.");
        }
    }
#endif

    public bool IsCoordinateInsideBuildingBounds(Vector3 targetPosition, float clearanceRadius)
    {
        if (buildingsRootNode == null) return false;

        foreach (Transform building in buildingsRootNode.GetComponentsInChildren<Transform>())
        {
            if (building == buildingsRootNode) continue;

            MeshRenderer renderer = building.GetComponent<MeshRenderer>();
            if (renderer != null)
            {
                Bounds expandedBounds = renderer.bounds;
                expandedBounds.Expand(clearanceRadius);

                if (expandedBounds.Contains(new Vector3(targetPosition.x, expandedBounds.center.y, targetPosition.z)))
                {
                    return true;
                }
            }
        }
        return false;
    }

    private Vector3 SnapToTerrain(Vector3 worldPos)
    {
        // Raycast down from 200m above to find actual terrain/Cesium height in the Editor
        Vector3 origin = new Vector3(worldPos.x, worldPos.y + 200f, worldPos.z);
        if (Physics.Raycast(origin, Vector3.down, out RaycastHit hit, 400f))
        {
            return hit.point;
        }
        return worldPos; // Fallback to original point height if no hit
    }

    [ContextMenu("🛣️ 2. Generate Complete Roads Network Mesh")]
    public void GenerateAllRoadMeshesProcedurally()
    {
        int roadAreaIndex = NavMesh.GetAreaFromName(roadAreaName);
        int layerIndex = LayerMask.NameToLayer(roadLayerName);
        if (layerIndex == -1) layerIndex = 0;

        // Clean up all existing Procedural_Roads_Container in the active scene (active and inactive) to prevent duplicate generation
        GameObject[] allObjects = Resources.FindObjectsOfTypeAll<GameObject>();
        foreach (var obj in allObjects)
        {
            if (obj != null && obj.name == "Procedural_Roads_Container" && obj.scene.name != null)
            {
                DestroyImmediate(obj);
            }
        }

        GameObject containerObject = new GameObject("Procedural_Roads_Container");
        containerObject.transform.SetParent(this.transform);
        containerObject.layer = layerIndex;

        List<Vector3> combinedVerts = new List<Vector3>();
        List<int> combinedTris = new List<int>();
        float halfWidth = roadWidth / 2f;
        int structuralSegmentCounter = 0;

        foreach (RoadPathSegment segment in roadSegments)
        {
            if (segment.roadCenterPoints == null || segment.roadCenterPoints.Count < 2) continue;

            for (int i = 0; i < segment.roadCenterPoints.Count - 1; i++)
            {
                Vector3 pA = segment.roadCenterPoints[i];
                Vector3 pB = segment.roadCenterPoints[i + 1];
                float segmentLength = Vector3.Distance(pA, pB);
                int divisions = Mathf.Max(1, Mathf.RoundToInt(segmentLength)); // 1 sub-division per meter

                for (int d = 0; d < divisions; d++)
                {
                    float tCurr = (float)d / divisions;
                    float tNext = (float)(d + 1) / divisions;

                    Vector3 rawCurr = Vector3.Lerp(pA, pB, tCurr);
                    Vector3 rawNext = Vector3.Lerp(pA, pB, tNext);

                    Vector3 currentPoint = SnapToTerrain(rawCurr);
                    Vector3 nextPoint = SnapToTerrain(rawNext);

                    Vector3 directionForward = (nextPoint - currentPoint).normalized;
                    Vector3 vectorRight = Vector3.Cross(Vector3.up, directionForward).normalized;

                    Vector3 v0 = currentPoint - (vectorRight * halfWidth);
                    Vector3 v1 = currentPoint + (vectorRight * halfWidth);
                    Vector3 v2 = nextPoint - (vectorRight * halfWidth);
                    Vector3 v3 = nextPoint + (vectorRight * halfWidth);

                    int indexOffset = combinedVerts.Count;
                    combinedVerts.Add(v0); combinedVerts.Add(v1); combinedVerts.Add(v2); combinedVerts.Add(v3);

                    combinedTris.Add(indexOffset + 0); combinedTris.Add(indexOffset + 2); combinedTris.Add(indexOffset + 1);
                    combinedTris.Add(indexOffset + 1); combinedTris.Add(indexOffset + 2); combinedTris.Add(indexOffset + 3);
                }
            }
            structuralSegmentCounter++;
        }

        if (combinedVerts.Count > 0)
        {
            MeshFilter mf = containerObject.AddComponent<MeshFilter>();
            MeshRenderer mr = containerObject.AddComponent<MeshRenderer>();

            mr.sharedMaterial = new Material(Shader.Find("Sprites/Default")) { color = new Color(0.25f, 0.25f, 0.25f, 1f) };

            Mesh roadMesh = new Mesh { name = "CombinedRoadMesh" };
            roadMesh.SetVertices(combinedVerts);
            roadMesh.SetTriangles(combinedTris, 0);
            roadMesh.RecalculateNormals();
            roadMesh.RecalculateBounds();

            mf.sharedMesh = roadMesh;
            containerObject.AddComponent<MeshCollider>().sharedMesh = roadMesh;

            NavMeshModifier modifier = containerObject.AddComponent<NavMeshModifier>();
            modifier.overrideArea = true;
            modifier.area = roadAreaIndex;
        }

        NavMeshSurface activeSurface = UnityEngine.Object.FindAnyObjectByType<NavMeshSurface>(FindObjectsInactive.Include);
        if (activeSurface != null)
        {
            containerObject.transform.SetParent(activeSurface.transform);
            // Trigger automatic NavMesh bake synchronously in the editor
            activeSurface.BuildNavMesh();
            Debug.Log("<color=green>[✔ NAVMESH AUTOMATED BAKE]</color> NavMesh rebuilt successfully.");
        }

        Debug.Log($"<color=green>[✔ ROAD NETWORK GENERATED]</color> Successfully compiled and combined {structuralSegmentCounter} branching road vectors into a single mesh.");
    }

