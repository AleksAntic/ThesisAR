    private void OnDrawGizmos()
    {
        if (roadSegments == null) return;
        float halfWidth = roadWidth / 2f;

        // 1. Render standard sequential road connections (Yellow/Cyan meshes skeleton)
        foreach (var segment in roadSegments)
        {
            if (segment.roadCenterPoints == null || segment.roadCenterPoints.Count == 0) continue;

            for (int i = 0; i < segment.roadCenterPoints.Count; i++)
            {
                Gizmos.color = Color.yellow;
                Gizmos.DrawSphere(segment.roadCenterPoints[i], 0.4f);

                if (i < segment.roadCenterPoints.Count - 1)
                {
                    Vector3 forward = (segment.roadCenterPoints[i + 1] - segment.roadCenterPoints[i]).normalized;
                    Vector3 right = Vector3.Cross(Vector3.up, forward).normalized;

                    Gizmos.color = Color.yellow;
                    Gizmos.DrawLine(segment.roadCenterPoints[i], segment.roadCenterPoints[i + 1]);

                    Gizmos.color = Color.cyan;
                    Gizmos.DrawLine(segment.roadCenterPoints[i] - (right * halfWidth), segment.roadCenterPoints[i] + (right * halfWidth));
                }
            }
        }

        // 2. LIVE GAP VISUALIZER CORE: Highlight unlinked points within detection thresholds in clear BLUE
        for (int sA = 0; sA < roadSegments.Count; sA++)
        {
            var segA = roadSegments[sA];
            if (segA.roadCenterPoints == null) continue;

            for (int pA = 0; pA < segA.roadCenterPoints.Count; pA++)
            {
                Vector3 posA = segA.roadCenterPoints[pA];

                for (int sB = sA; sB < roadSegments.Count; sB++)
                {
                    var segB = roadSegments[sB];
                    if (segB.roadCenterPoints == null) continue;

                    int startPtB = (sA == sB) ? pA + 2 : 0;

                    for (int pB = startPtB; pB < segB.roadCenterPoints.Count; pB++)
                    {
                        Vector3 posB = segB.roadCenterPoints[pB];
                        float scalarDistance = Vector3.Distance(posA, posB);

                        if (scalarDistance > 0.05f && scalarDistance <= gapDetectionRadius)
                        {
                            Gizmos.color = Color.blue;
                            Gizmos.DrawLine(posA, posB);
                            Gizmos.DrawWireSphere(posA, 0.45f);
                            Gizmos.DrawWireSphere(posB, 0.45f);
                        }
                    }
                }
            }
        }
    }
