    [ContextMenu("🧹 3. Clean Existing Cubes Under Buildings")]
    public void CleanExistingCubesUnderBuildings()
    {
        GameObject rootCubes = GameObject.Find("Procedural_NavMesh_Modifiers_Root");
        if (rootCubes == null)
        {
            Debug.LogError("[Automator Optimization] Could not find the object 'Procedural_NavMesh_Modifiers_Root' in the active scene. Generate the grid first.");
            return;
        }

        int notWalkableArea = NavMesh.GetAreaFromName("Not Walkable");
        int fixedCounter = 0;

        Transform[] allCubes = rootCubes.GetComponentsInChildren<Transform>(true);
        foreach (Transform cube in allCubes)
        {
            if (cube == rootCubes.transform) continue;

            if (IsCoordinateInsideBuildingBounds(cube.position, 0.1f))
            {
                NavMeshModifier modifier = cube.GetComponent<NavMeshModifier>();
                if (modifier != null && modifier.area != notWalkableArea)
                {
                    UnityEditor.Undo.RecordObject(modifier, "Carve Building Footprint");
                    modifier.area = notWalkableArea;
                    fixedCounter++;
                }
            }
        }

        Debug.Log($"<color=green>[✔ SCENE CLEANUP COMPLETE]</color> Audited existing modifiers. Successfully forced {fixedCounter} overlapping grass cubes to become 'Not Walkable' underneath your building placeholders!");
    }

    [ContextMenu("⚡ 4. Auto-Bridge Close Road Gaps (< 5m)")]
    public void AutoBridgeCloseRoadGaps()
    {
        if (roadSegments == null || roadSegments.Count == 0) return;

        UnityEditor.Undo.RecordObject(this, "Auto-Bridge Unlinked Road Gaps");
        int createdBridgesCount = 0;
        List<System.Collections.Generic.KeyValuePair<Vector3, Vector3>> detectedBridges = new List<System.Collections.Generic.KeyValuePair<Vector3, Vector3>>();

        // High-performance nested matrix lookup to isolate unlinked nodes within proximity bounds
        for (int sA = 0; sA < roadSegments.Count; sA++)
        {
            var segA = roadSegments[sA];
            if (segA.roadCenterPoints == null) continue;

            for (int pA = 0; pA < segA.roadCenterPoints.Count; pA++)
            {
                Vector3 posA = segA.roadCenterPoints[pA];

                for (int sB = sA; sB < roadSegments.Count; sB++)
                {
                    var segB = roadSegments[sB];
                    if (segB.roadCenterPoints == null) continue;

                    // Skip direct sequential neighbors inside the same road array path
                    int startPtB = (sA == sB) ? pA + 2 : 0;

                    for (int pB = startPtB; pB < segB.roadCenterPoints.Count; pB++)
                    {
                        Vector3 posB = segB.roadCenterPoints[pB];
                        float scalarDistance = Vector3.Distance(posA, posB);

                        if (scalarDistance > 0.05f && scalarDistance <= gapDetectionRadius)
                        {
                            detectedBridges.Add(new System.Collections.Generic.KeyValuePair<Vector3, Vector3>(posA, posB));
                        }
                    }
                }
            }
        }

        // Generate independent micro-bridge mesh injectors over the topology network
        foreach (var bridge in detectedBridges)
        {
            createdBridgesCount++;
            RoadPathSegment bridgeSegment = new RoadPathSegment
            {
                roadLabelName = $"AutoBridge_Link_{createdBridgesCount}",
                roadCenterPoints = new List<Vector3> { bridge.Key, bridge.Value }
            };
            roadSegments.Add(bridgeSegment);
        }

        if (createdBridgesCount > 0)
        {
            GenerateAllRoadMeshesProcedurally();
            Debug.Log($"<color=green>[✔ AUTO-PATCH SUCCESS]</color> Successfully patched {createdBridgesCount} geometric gaps below {gapDetectionRadius} meters by injecting micro-bridge mesh segments.");
        }
        else
        {
            UnityEditor.EditorUtility.DisplayDialog("Auto-Bridge Engine", "No unlinked road gaps below the specified distance threshold were detected.", "OK");
        }
    }
